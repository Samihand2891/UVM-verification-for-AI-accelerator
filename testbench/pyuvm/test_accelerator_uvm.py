import random

import cocotb
import pyuvm
from cocotb.clock import Clock
from cocotb.triggers import FallingEdge, RisingEdge, Timer
from pyuvm import uvm_test

from environment import AcceleratorEnvironment
from matrix_item import MatrixOperation
from Sequencer import (
    BusyWriteIgnoredSequence,
    InvalidKSequence,
    SingleOperationSequence,
)


SEED = 20261115


@pyuvm.test()
class AcceleratorDirectedTest(uvm_test):
    def build_phase(self):
        self.env = AcceleratorEnvironment.create("env", self)

    async def reset_dut(self, dut):
        await FallingEdge(dut.clk)
        dut.a_we.value = 0
        dut.b_we.value = 0
        dut.start.value = 0
        dut.rst_n.value = 0
        for _ in range(2):
            await RisingEdge(dut.clk)
        await FallingEdge(dut.clk)
        dut.rst_n.value = 1
        await Timer(1, unit="ns")
        assert int(dut.busy.value) == 0
        assert int(dut.done.value) == 0
        assert int(dut.error.value) == 0
        assert int(dut.result_valid.value) == 0

    async def run_operation(self, name, operation):
        sequence = SingleOperationSequence(name=name, operation=operation)
        await sequence.start(self.env.agent.sequencer)

    async def run_phase(self):
        self.raise_objection("Run directed and seeded matrix operations")

        dut = cocotb.top
        dut.clk.value = 0
        dut.rst_n.value = 0
        dut.a_we.value = 0
        dut.a_row.value = 0
        dut.a_k.value = 0
        dut.a_wdata.value = 0
        dut.b_we.value = 0
        dut.b_k.value = 0
        dut.b_col.value = 0
        dut.b_wdata.value = 0
        dut.start.value = 0
        dut.k_len.value = 0
        dut.result_addr.value = 0
        cocotb.start_soon(Clock(dut.clk, 10, unit="ns").start())
        await Timer(1, unit="ns")
        await self.reset_dut(dut)

        # Smallest supported K.
        await self.run_operation(
            "k1_sequence",
            MatrixOperation(
                name="k1_operation",
                k_len=1,
                matrix_a=[[1], [2], [-3], [4]],
                matrix_b=[[5, -6, 7, 0]],
            ),
        )

        # Largest supported K, retaining the existing busy-write rejection probe.
        await BusyWriteIgnoredSequence("busy_write_ignored_sequence").start(
            self.env.agent.sequencer
        )

        # Invalid requests are isolated by reset so no previous result can be
        # mistaken for a result generated by the rejected request.
        for invalid_k in (0, 65):
            await self.reset_dut(dut)
            await InvalidKSequence(k_len=invalid_k).start(
                self.env.agent.sequencer
            )
            self.logger.info("PASS: invalid K=%d rejected without a result", invalid_k)

        # A valid operation after reset proves the controller and memories recover.
        await self.reset_dut(dut)
        await self.run_operation(
            "reset_recovery_sequence",
            MatrixOperation(
                name="reset_recovery_operation",
                k_len=2,
                matrix_a=[[1, 2], [3, 4], [5, 6], [7, 8]],
                matrix_b=[[1, 0, -1, 2], [3, -2, 1, 0]],
            ),
        )

        # Explicit INT8 signed corners plus -1 and 0.
        await self.run_operation(
            "signed_corner_sequence",
            MatrixOperation(
                name="signed_corner_operation",
                k_len=4,
                matrix_a=[
                    [-128, 127, -1, 0],
                    [127, -128, 0, -1],
                    [-1, 0, -128, 127],
                    [0, -1, 127, -128],
                ],
                matrix_b=[
                    [1, -1, 0, 127],
                    [-1, 1, -128, 0],
                    [127, 0, 1, -1],
                    [0, -128, -1, 1],
                ],
            ),
        )

        # Reproducible randomized matrix operations; the seed is printed so a
        # failing run can be recreated exactly.
        rng = random.Random(SEED)
        self.logger.info("Seeded random tests use seed=%d", SEED)
        for index in range(3):
            k_len = rng.choice((1, 2, 3, 7, 16, 32, 64))
            matrix_a = [
                [rng.randint(-128, 127) for _ in range(k_len)]
                for _ in range(4)
            ]
            matrix_b = [
                [rng.randint(-128, 127) for _ in range(4)]
                for _ in range(k_len)
            ]
            await self.run_operation(
                f"random_seed_{SEED}_{index}",
                MatrixOperation(
                    name=f"random_operation_{index}_k{k_len}",
                    k_len=k_len,
                    matrix_a=matrix_a,
                    matrix_b=matrix_b,
                ),
            )

        assert int(dut.error.value) == 0
        assert int(dut.busy.value) == 0
        assert int(dut.result_valid.value) == 1
        self.logger.info("PASS: directed tests and 3 seeded random operations")
        self.drop_objection("All operations completed")
